-- =========================
-- 8. MANAGER HELPER
-- =========================
create or replace function public.is_manager()
returns boolean
language sql
security definer
stable
set search_path = ''
as $$
  select exists (
    select 1
    from public.users
    where id = (select auth.uid())
      and role = 'manager'
      and is_active = true
  );
$$;

revoke all on function public.is_manager() from public;
grant execute on function public.is_manager() to authenticated;

-- =========================
-- 9. PAYROLL VIEW
-- =========================
-- security_invoker = true là bắt buộc để view tôn trọng RLS của các bảng nguồn.
create or replace view public.v_payroll_days
with (security_invoker = true)
as
with keys as (
  select user_id, work_date
  from public.shifts
  where status = 'approved'
),
base as (
  select
    u.id as user_id,
    u.emp_code,
    u.full_name,
    u.position,
    coalesce(r.hourly_rate, 0) as hourly_rate,
    coalesce(r.allowance_per_shift, 0) as allowance_per_shift,
    k.work_date,
    a.check_in_1,
    a.check_out_1,
    a.check_in_2,
    a.check_out_2,
    n.note_text,
    coalesce(n.adjustment_amount, 0) as adjustment_amount
  from keys k
  join public.users u on u.id = k.user_id
  left join public.roles_rates r on r.user_id = u.id
  left join public.attendance_logs a
    on a.user_id = k.user_id and a.work_date = k.work_date
  left join public.daily_notes n
    on n.user_id = k.user_id and n.note_date = k.work_date
)
select * from base;

