-- 10. APPROVED LEAVE => REJECT SHIFT
-- =========================
create or replace function public.on_leave_approved()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status = 'approved' and old.status is distinct from 'approved' then
    new.approved_by := (select auth.uid());
    new.approved_at := now();

    update public.shifts
       set status = 'rejected',
           updated_at = now()
     where user_id = new.user_id
       and work_date = new.leave_date
       and status <> 'rejected';

  end if;
  return new;
end;
$$;

drop trigger if exists trg_leave_approved on public.leave_requests;
create trigger trg_leave_approved
before update on public.leave_requests
for each row execute function public.on_leave_approved();

-- =========================
-- 11. LOGIN IDENTIFIER RESOLVER
-- =========================
-- Frontend dùng mã NV hoặc số điện thoại -> backend/auth email ảo.
create or replace function public.resolve_login(identifier text)
returns text
language sql
security definer
stable
set search_path = ''
as $$
  select lower(emp_code) || '@company.local'
  from public.users
  where is_active = true
    and (
      lower(emp_code) = lower(trim(identifier))
      or phone = trim(identifier)
    )
  limit 1;
$$;

revoke all on function public.resolve_login(text) from public;
grant execute on function public.resolve_login(text) to anon, authenticated;

