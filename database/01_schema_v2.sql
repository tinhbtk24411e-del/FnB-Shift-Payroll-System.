-- ============================================================
-- F&B Shift + Attendance + Payroll System
-- Supabase / PostgreSQL - V2
--
-- Dùng cho PROJECT MỚI. Không chạy đè lên 01_schema.sql cũ nếu
-- database hiện tại đã có dữ liệu. Với database cũ, cần migration riêng.
--
-- Thiết kế V2:
--   users                : hồ sơ + quyền + device_pin
--   roles_rates          : lương giờ + phụ cấp/ca
--   shifts               : lịch/ca nhân viên đăng ký
--   attendance_punches   : dữ liệu QUẸT THÔ từ máy chấm công (audit)
--   attendance_logs      : dữ liệu ĐÃ GHÉP thành tối đa 2 cặp vào/ra/ngày
--   leave_requests       : đơn nghỉ
--   daily_notes          : NOTE + khoản điều chỉnh theo ngày
--   v_payroll_days       : view dùng chung cho PWA + Excel
--
-- Quy tắc payroll:
--   GIỜ CÔNG = (Ra1 - Vào1) + (Ra2 - Vào2)
--   LƯƠNG NGÀY = GIỜ CÔNG * LƯƠNG GIỜ + PHỤ CẤP
--   TỔNG THU NHẬP = LƯƠNG THÁNG - tổng NOTE dương
--   NOTE âm = cộng bù
--
-- Quan trọng: payroll dùng giờ CHẤM CÔNG THỰC TẾ. Ca đã duyệt nhưng
-- chưa có attendance không tự động tạo giờ công/lương; quản lý có thể
-- sửa attendance sau ở phase tiếp theo.
-- ============================================================

create extension if not exists pgcrypto;

-- =========================
-- 1. USERS / HRM
-- =========================
create table public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  emp_code text unique not null,
  full_name text not null,
  phone text unique,
  position text,
  role text not null default 'employee'
    check (role in ('employee','manager')),
  device_pin text unique,
  bank_name text,
  bank_account_no text,
  bank_account_name text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.roles_rates (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique references public.users(id) on delete cascade,
  hourly_rate numeric(12,0) not null default 0 check (hourly_rate >= 0),
  allowance_per_shift numeric(12,0) not null default 0 check (allowance_per_shift >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- =========================
-- 2. SHIFT REGISTRATION
-- =========================
create table public.shifts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  work_date date not null,
  check_in_1 time,
  check_out_1 time,
  check_in_2 time,
  check_out_2 time,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, work_date),
  check ((check_in_1 is null and check_out_1 is null) or (check_in_1 is not null and check_out_1 is not null)),
  check ((check_in_2 is null and check_out_2 is null) or (check_in_2 is not null and check_out_2 is not null))
);

-- =========================
-- 3. RAW ATTENDANCE PUNCHES
-- =========================
create table public.attendance_punches (
  id bigint generated by default as identity primary key,
  user_id uuid references public.users(id) on delete set null,
  device_id text not null,
  device_pin text not null,
  punched_at timestamptz not null,
  verify_type text,
  raw_status text,
  created_at timestamptz not null default now(),
  unique (device_id, device_pin, punched_at)
);

create index attendance_punches_user_time_idx
  on public.attendance_punches(user_id, punched_at);

create index attendance_punches_device_pin_time_idx
  on public.attendance_punches(device_id, device_pin, punched_at);

-- =========================
-- 4. DAILY ATTENDANCE SUMMARY
-- =========================
-- Một dòng / nhân viên / ngày, đã ghép tối đa 2 cặp vào-ra.
-- Bảng này là lớp trung gian để frontend và Excel đọc nhanh.
create table public.attendance_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  work_date date not null,
  device_id text,
  check_in_1 time,
  check_out_1 time,
  check_in_2 time,
  check_out_2 time,
  punch_count integer not null default 0 check (punch_count >= 0),
  source text not null default 'device'
    check (source in ('device','manual','adjusted')),
  synced_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, work_date)
);

create index attendance_logs_date_idx
  on public.attendance_logs(work_date);

-- =========================
-- 5. LEAVE REQUESTS
-- =========================
create table public.leave_requests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  leave_date date not null,
  reason text,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected')),
  approved_by uuid references public.users(id),
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index leave_requests_date_status_idx
  on public.leave_requests(leave_date, status);

-- =========================
-- 6. DAILY NOTE / ADJUSTMENT
-- =========================
-- adjustment_amount > 0  => TRỪ tiền
-- adjustment_amount < 0  => CỘNG/bù tiền
create table public.daily_notes (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  note_date date not null,
  note_text text,
  adjustment_amount numeric(12,0) not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, note_date)
);

create index daily_notes_user_date_idx
  on public.daily_notes(user_id, note_date);

